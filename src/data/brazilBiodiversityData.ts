/**
 * Retorna todos os espécimes associados a um estado ou bioma específico
 */
export function getSpecimensByState(stateId: string): BiodiversitySpecimen[] {
  return ALL_BRAZIL_SPECIMENS.filter((specimen) => specimen.states.includes(stateId));
}

export function getSpecimensByBiome(biome: BrazilBiome): BiodiversitySpecimen[] {
  return ALL_BRAZIL_SPECIMENS.filter((specimen) => specimen.biomes.includes(biome));
}

export function getSpecimensByKingdom(kingdom: 'fauna' | 'flora' | 'fungi_micro'): BiodiversitySpecimen[] {
  return ALL_BRAZIL_SPECIMENS.filter((specimen) => specimen.kingdom === kingdom);
}

